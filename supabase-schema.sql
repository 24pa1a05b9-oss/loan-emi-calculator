CREATE TABLE IF NOT EXISTS public.loan_calculations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  loan_name TEXT NOT NULL DEFAULT 'General Loan',
  principal NUMERIC(15, 2) NOT NULL CHECK (principal > 0),
  annual_interest_rate NUMERIC(7, 4) NOT NULL CHECK (annual_interest_rate >= 0),
  tenure_months INTEGER NOT NULL CHECK (tenure_months > 0),
  monthly_emi NUMERIC(15, 2) NOT NULL CHECK (monthly_emi > 0),
  total_interest NUMERIC(15, 2) NOT NULL CHECK (total_interest >= 0),
  total_payment NUMERIC(15, 2) NOT NULL CHECK (total_payment >= principal),
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- Create index on created_at for fast descending history queries
CREATE INDEX IF NOT EXISTS idx_loan_calculations_created_at
  ON public.loan_calculations (created_at DESC);

-- Enable Row Level Security (RLS)
ALTER TABLE public.loan_calculations ENABLE ROW LEVEL SECURITY;

-- Policies for public or service role access
CREATE POLICY "Allow read access to loan calculations"
  ON public.loan_calculations FOR SELECT
  USING (true);

CREATE POLICY "Allow insert access to loan calculations"
  ON public.loan_calculations FOR INSERT
  WITH CHECK (true);

CREATE POLICY "Allow delete access to loan calculations"
  ON public.loan_calculations FOR DELETE
  USING (true);
